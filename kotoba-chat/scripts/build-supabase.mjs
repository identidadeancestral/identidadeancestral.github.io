import {build} from 'esbuild';
import {mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const out=new URL('../backend/supabase/dist/',import.meta.url);
await mkdir(out,{recursive:true});
await build({absWorkingDir:root,entryPoints:['backend/supabase/edge.ts'],outfile:fileURLToPath(new URL('index.ts',out)),bundle:true,format:'esm',platform:'neutral',target:'es2022',minify:false,sourcemap:false,external:['node:crypto','node:buffer'],plugins:[{name:'postgres-deno',setup(b){b.onResolve({filter:/^postgres$/},()=>({path:'npm:postgres@3.4.7',external:true}));}}],banner:{js:'// @ts-nocheck\n// Generated by scripts/build-supabase.mjs. Deploy as ojiisan-api.'}});
await writeFile(new URL('deno.json',out),JSON.stringify({nodeModulesDir:'auto'},null,2)+'\n');
console.log('Supabase function bundle prepared. Not deployed.');
